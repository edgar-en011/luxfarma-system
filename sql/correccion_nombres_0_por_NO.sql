INSERT INTO productos_log_renombre (id_producto, nombre_anterior, nombre_nuevo, origen)
SELECT r.id_producto, r.nombre_anterior, r.nombre_nuevo, 'correccion_masiva_0_por_N_O'
FROM _renombres r
WHERE NOT EXISTS (
  SELECT 1 FROM productos_log_renombre l
  WHERE l.id_producto = r.id_producto
    AND l.nombre_anterior = r.nombre_anterior
    AND l.nombre_nuevo = r.nombre_nuevo
    AND l.origen = 'correccion_masiva_0_por_N_O'
);

UPDATE productos p
SET descripcion = r.nombre_nuevo
FROM _renombres r
WHERE p.id_producto = r.id_producto
  AND p.descripcion IS DISTINCT FROM r.nombre_nuevo;

