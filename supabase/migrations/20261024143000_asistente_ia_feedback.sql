CREATE TABLE IF NOT EXISTS public.asistente_ia_feedback (
  id_feedback bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sesion uuid NOT NULL REFERENCES public.asistente_ia_sesiones(id_sesion) ON DELETE CASCADE,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
  respuesta_id text NOT NULL CHECK (length(respuesta_id) BETWEEN 8 AND 80),
  util boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT asistente_ia_feedback_sesion_respuesta_key UNIQUE (id_sesion, respuesta_id)
);

CREATE INDEX IF NOT EXISTS idx_asistente_ia_feedback_created_at
  ON public.asistente_ia_feedback (created_at DESC);

ALTER TABLE public.asistente_ia_feedback ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.asistente_ia_feedback FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.asistente_ia_feedback TO service_role;

COMMENT ON TABLE public.asistente_ia_feedback IS
  'Valoración agregada de utilidad del asistente; no guarda preguntas ni respuestas.';
